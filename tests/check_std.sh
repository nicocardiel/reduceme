#!/bin/sh
# Check that the Fortran sources conform to the Fortran 2018 standard, i.e.
# that no compiler extensions are used (called by "make check-std").
# Requires gfortran. Obsolescent (but standard) features are not reported.
#
# The library modules (which include the files with the procedures) are
# compiled first, in dependency order, and then every program.
#
# Usage: check_std.sh [FC [TOP_SRCDIR [TOP_BUILDDIR]]]
FC=${1:-gfortran}
SRC=${2:-.}
BUILD=${3:-.}
# -Werror=intrinsics-std: GNU intrinsic procedures (GETENV, SYSTEM, RAND...)
# would otherwise be silently treated as external procedures. (-w cannot be
# used to hide the obsolescence warnings: it would also hide these errors.)
FLAGS="-std=f2018 -Werror=intrinsics-std -fsyntax-only"
# module files written by the check go to a temporary directory
MODDIR=`mktemp -d "${TMPDIR:-/tmp}/check_std.XXXXXX"` || exit 1
trap 'rm -rf "$MODDIR"' EXIT
nfiles=0
nbad=0
check() {
  # $1: directory, $2: source file
  nfiles=`expr $nfiles + 1`
  if ! out=`$FC $FLAGS -J"$MODDIR" -I"$MODDIR" -I"$BUILD/$1" -I"$SRC/$1" \
      "$2" 2>&1`; then
    nbad=`expr $nbad + 1`
    # print only the diagnostic blocks that end with an error
    printf '%s\n' "$out" | awk '
      /^Error:|Fatal Error:/ { printf "%s%s\n", block, $0; block = ""; next }
      /^Warning:/ { block = ""; next }
      { block = block $0 "\n" }'
  fi
}
# redlib_m.f90 is generated by configure in the build tree
check futils "$BUILD/futils/redlib_m.f90"
for lib in futils button fspec red; do
  # data modules of the library (used by its module) are compiled first
  for f in "$SRC/$lib"/*_data_m.f90; do
    test -f "$f" && check $lib "$f"
  done
  check $lib "$SRC/$lib/${lib}_m.f90"
done
if test $nbad -ne 0; then
  # the programs cannot be checked without the library modules
  echo "check-std: $nbad library module(s) with errors; programs not checked"
  exit 1
fi
for f in "$SRC"/src/*.f90; do
  check src "$f"
done
echo "check-std: $nfiles files checked, $nbad with non-standard code"
test $nbad -eq 0
